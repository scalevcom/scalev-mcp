import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const docsRoot = path.resolve(repoRoot, "..", "dev-docs");
const outputPath = path.resolve(repoRoot, "src", "generated", "docsCatalog.ts");
const generatedDocs = [];
const sourceHashes = [];
const seenTopics = new Set();
const TOPIC_OVERRIDES = {
  introduction: "dev_introduction",
  "authorization-with-o-auth": "oauth_authorization"
};

for (const category of await readOrder("docs/_order.yaml")) {
  for (const slug of await readOrder(`docs/${category}/_order.yaml`)) {
    const relativePath = `docs/${category}/${slug}.md`;
    const source = `../dev-docs/${relativePath}`;
    const raw = await readFile(path.resolve(docsRoot, relativePath), "utf8");
    const sourceSha256 = sha256(raw);
    sourceHashes.push(`${source}:${sourceSha256}`);
    const { frontmatter, body } = splitFrontmatter(raw);
    if (frontmatter.hidden === true) continue;

    const topic = TOPIC_OVERRIDES[slug] || slug.replace(/[^a-zA-Z0-9]+/g, "_").toLowerCase();
    if (seenTopics.has(topic)) throw new Error(`Duplicate docs topic: ${topic}`);
    seenTopics.add(topic);
    const title = frontmatter.title || slug;
    generatedDocs.push({
      topic,
      title,
      description: frontmatter.excerpt,
      language: "en",
      slug,
      nav_group: category,
      nav_path: ["Guide", category],
      url: `https://docs.scalev.dev/docs/${slug}`,
      source,
      source_sha256: sourceSha256,
      hint: `Scalev Developers doc: Guide / ${category} / ${title}.`,
      content: body.replace(/\]\(\/docs\//g, "](https://docs.scalev.dev/docs/").trim()
    });
  }
}

if (generatedDocs.length === 0) throw new Error("No public guides found in dev-docs navigation");
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `// Generated by scripts/generate-docs-catalog.mjs from ../dev-docs.
// Do not edit by hand.

import type { ScalevDoc } from "../docs";

export const DOCS_CATALOG_SOURCE_SHA256 = ${JSON.stringify(sha256(sourceHashes.join("\n")))};

export const SCALEV_DOCS = ${JSON.stringify(generatedDocs, null, 2)} as const satisfies readonly ScalevDoc[];
`);
console.log(`Generated ${path.relative(repoRoot, outputPath)} with ${generatedDocs.length} docs`);

async function readOrder(relativePath) {
  const raw = await readFile(path.resolve(docsRoot, relativePath), "utf8");
  sourceHashes.push(`../dev-docs/${relativePath}:${sha256(raw)}`);
  const entries = parse(raw);
  if (!Array.isArray(entries) || entries.some((entry) => typeof entry !== "string")) {
    throw new Error(`Invalid docs navigation: ${relativePath}`);
  }
  return entries;
}

function splitFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)([\s\S]*)$/);
  if (!match) throw new Error("Guide is missing YAML frontmatter");
  return { frontmatter: parse(match[1]), body: match[2] };
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}
